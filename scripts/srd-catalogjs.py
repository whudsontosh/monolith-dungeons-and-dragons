"""Writes src/catalog.js from catalog.json (spells, equipment and starting kits from the SRD 5.2)."""
import json, sys
d = json.load(open(sys.argv[1]))
# The Foundry data leaves out the gold in the backgrounds' option A; these are the SRD 5.2 amounts
# ("Acolyte ... Robe, 8 GP; or (B) 50 GP", and so on).
BG_GP = {"Acolyte": 8, "Criminal": 16, "Sage": 8, "Soldier": 14}
for name, opts in d["kits"]["bg"].items():
    if opts and opts[0]["items"] and not opts[0]["gp"] and name in BG_GP: opts[0]["gp"] = BG_GP[name]
for group in d["kits"].values():
    for opts in group.values():
        for o in opts: o["gp"] = int(o["gp"] or 0)
j = lambda x: json.dumps(x, ensure_ascii=False, separators=(",", ":"))
js = """/* ============================== D&D 2024: SPELLS, EQUIPMENT AND STARTING KITS (GENERATED) ==============================
   Every SRD spell (with its class lists and main damage roll), the equipment and magic items, and
   each class's and background's starting equipment options. Generated by scripts/srd-catalog.py and
   scripts/srd-catalogjs.py from the Foundry VTT dnd5e system's SRD 5.2 data. Don't edit by hand.

   This work includes material from the System Reference Document 5.2 ("SRD 5.2") by Wizards of the
   Coast LLC, available at https://www.dndbeyond.com/srd. The SRD 5.2 is licensed under the Creative
   Commons Attribution 4.0 International License, https://creativecommons.org/licenses/by/4.0/legalcode. */
const DND_SPELLS = %s;
const DND_ITEMS = %s;
const DND_KITS = %s;
""" % (j(d["spells"]), j(d["items"]), j(d["kits"]))
open(sys.argv[2], "w", encoding="utf-8").write(js)
print(len(js) // 1024, "KB")

"""The character sheet: the example character, rolls with advantage, damage and death saves, rests, spells, a new character, and the GM's party table."""
import asyncio, sys, os
from playwright.async_api import async_playwright
from harness import *

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        pl = await page(b, "P", "player.html")
        ok(await pl.locator(".card:has-text('Ilyra Venn')").count() == 1, "the example character is on the roster")
        await pl.click(".card:has-text('Ilyra Venn') [data-act=open-char]"); await pl.wait_for_timeout(300)
        await pl.screenshot(path=OUT + "/s1-sample.png", full_page=True)
        k = await pl.evaluate("(()=>{const k=dndCalc(curChar());return [k.pb,k.mod.int,k.save.int,k.skill.arcana,k.skill.perception,k.passive.perception,k.hpMax,k.spellDc,k.spellAtk,k.slots.slice(1,4),k.init]})()")
        print(k)
        ok(k == [2, 3, 5, 5, 3, 13, 20, 13, 5, [4, 2], 2], "level 3 wizard numbers: prof +2, INT +3, Arcana +5, PP 13, HP 20, DC 13, slots 4/2")
        await pl.click("[data-act=copy-sample]"); await pl.wait_for_timeout(400)
        cid = await pl.evaluate("curChar().id")
        ok(cid != "sample" and await pl.evaluate("canEditChar(curChar())"), "copied the example to an editable character")
        # rolls
        await pl.evaluate("Math.random=()=>0.95"); await pl.click("[data-act=dnd-skill][data-s=arcana]"); await pl.wait_for_timeout(150)
        e = await pl.evaluate("Dice.log[0]"); print(e)
        ok(e["label"] == "Arcana" and e["total"] == 25 and e["tags"][0]["t"] == "Natural 20", "Arcana roll: 20 + 5 with a natural 20 tag")
        await pl.click("[data-act=dnd-adv][data-m=dis]"); await pl.wait_for_timeout(100)
        await pl.evaluate("(()=>{let i=0;const v=[0.95,0.1];Math.random=()=>v[(i++)%2]})()")
        await pl.click("[data-act=dnd-save][data-a=wis]"); await pl.wait_for_timeout(150)
        e = await pl.evaluate("Dice.log[0]"); print(e)
        ok("disadvantage (20, 3)" in e["detail"] and e["total"] == 3 + 3, "disadvantage keeps the lower die, and the switch resets: " + e["detail"])
        ok(await pl.evaluate("ui.dndAdv") == "normal", "advantage switch is back to normal after one roll")
        await pl.evaluate("Math.random=()=>0.5")
        await pl.click("[data-act=dnd-attack][data-i='0']", modifiers=["Shift"]); await pl.wait_for_timeout(150)
        e = await pl.evaluate("Dice.log[0]"); ok("advantage" in e["detail"] and e["total"] == 11 + 4, "Shift+click dagger: advantage, +4 to hit (DEX +2, prof +2)")
        await pl.click("[data-act=dnd-crit][data-i='0']"); await pl.wait_for_timeout(150)
        e = await pl.evaluate("Dice.log[0]"); print(e); ok("2d4" in e["detail"] and e["total"] == 3 + 3 + 2, "critical dagger damage doubles the dice and adds DEX once")
        # damage & healing
        await pl.fill(f"#dnd-amt-{cid}", "8"); await pl.click("[data-act=dnd-dmg]"); await pl.wait_for_timeout(200)
        ok(await pl.evaluate("dndCalc(curChar()).hp") == 12, "8 damage: 20 → 12")
        await pl.fill(f"#dnd-amt-{cid}", "30"); await pl.click("[data-act=dnd-dmg]"); await pl.wait_for_timeout(200)
        st = await pl.evaluate("(()=>{const c=curChar();return [dndCalc(c).hp,c.conditions,c.death.f]})()"); print(st)
        ok(st[0] == 0 and "Unconscious" in st[1] and st[2] == 0, "dropping to 0 knocks them unconscious (not massive damage: 18 left over < 20)")
        await pl.screenshot(path=OUT + "/s2-dying.png", full_page=True)
        await pl.evaluate("Math.random=()=>0.6"); await pl.click("[data-act=dnd-deathroll]"); await pl.wait_for_timeout(150)
        ok(await pl.evaluate("curChar().death.s") == 1, "death save 13: one success")
        await pl.click("[data-act=dnd-long]"); await pl.wait_for_timeout(200)
        st = await pl.evaluate("(()=>{const c=curChar();return [dndCalc(c).hp,c.conditions,c.death]})()")
        ok(st[0] == 20 and st[1] == [] and st[2] == {"s": 0, "f": 0}, "long rest: full HP, conscious, death saves cleared")
        # spells
        await pl.click("[data-act=dnd-tab][data-t=spells]"); await pl.wait_for_timeout(200)
        await pl.click(".dnd-spell:has(input[value='Misty Step']) [data-act=dnd-cast]"); await pl.wait_for_timeout(150)
        ok(await pl.evaluate("curChar().slotsUsed[2]") == 1, "casting Misty Step spends a 2nd-level slot")
        await pl.click(".dnd-spell:has(input[value='Shield']) [data-act=dnd-cast]"); await pl.wait_for_timeout(150)
        ok(await pl.evaluate("curChar().slotsUsed[1]") == 1, "casting Shield spends a 1st-level slot")
        await pl.select_option("#dnd-newlvl", "3"); await pl.fill("#dnd-newspell", "Fireball"); await pl.press("#dnd-newspell", "Enter"); await pl.wait_for_timeout(200)
        ok(await pl.evaluate("curChar().spells.some(s=>s.name==='Fireball'&&s.lvl===3)"), "added Fireball as a 3rd-level spell with Enter")
        await pl.screenshot(path=OUT + "/s3-spells.png", full_page=True)
        await pl.click("[data-act=dnd-tab][data-t=inv]"); await pl.wait_for_timeout(200); await pl.screenshot(path=OUT + "/s4-inv.png", full_page=True)
        # a new character: details first, class sets saves
        await pl.click("nav [data-act=go-roster]"); await pl.wait_for_timeout(200)
        await pl.click("[data-act=new-character] >> nth=0"); await pl.wait_for_timeout(300)
        await pl.click("[data-act=dnd-b-skip]"); await pl.wait_for_timeout(300)
        ok(await pl.evaluate("ui.dndTab") == "details", "skipping the creator opens the sheet's Details tab")
        await pl.fill("[data-dnd=name]", "Thorek"); await pl.select_option("[data-dnd=cls]", "Fighter"); await pl.wait_for_timeout(200)
        await pl.fill("[data-dnd=level]", "5"); await pl.fill("[data-dnd=species]", "Goliath"); await pl.wait_for_timeout(300)
        c = await pl.evaluate("(()=>{const c=curChar();const k=dndCalc(c);return [c.saveProf.str,c.saveProf.con,c.saveProf.dex,k.pb,k.speed,k.hpMax,k.slots.length]})()"); print(c)
        ok(c == [True, True, False, 3, 35, 10 + 4 * 6, 1], "Fighter 5: STR/CON saves, prof +3, Goliath 35 ft, HP 34, no slots")
        await pl.screenshot(path=OUT + "/s5-details.png", full_page=True)
        await pl.click("[data-act=dnd-tab][data-t=sheet]"); await pl.wait_for_timeout(200)
        await pl.fill("[data-dnd='ab.str']", "16"); await pl.wait_for_timeout(200)
        ok(await pl.evaluate("dndCalc(curChar()).save.str") == 6, "STR 16 with proficiency: save +6")
        await pl.wait_for_timeout(900)
        saved = await pl.evaluate("JSON.parse(localStorage.getItem('monolith-roster-dnd')).find(c=>c.name==='Thorek')")
        ok(saved and saved["ab"]["str"] == 16 and saved["ruleset"] == "dnd5.5e", "saved with its ruleset")
        await pl.set_viewport_size({"width": 420, "height": 900}); await pl.wait_for_timeout(200)
        await pl.screenshot(path=OUT + "/s6-phone.png", full_page=True)
        await pl.set_viewport_size({"width": 1440, "height": 900})
        # GM
        gm = await page(b, "GM", "gm.html")
        await gm.evaluate("x=>{st.party.push(dndNormalize(x));save(true);render()}", await pl.evaluate("clone(S.chars.get(arguments[0]))", cid) if False else await pl.evaluate("(id)=>clone(S.chars.get(id))", cid))
        await gm.wait_for_timeout(300)
        ok(await gm.locator("table.dnd-party tr:has-text('Ilyra Venn')").count() == 1, "the GM's party table lists the character")
        await gm.screenshot(path=OUT + "/s7-gm-party.png", full_page=True)
        await gm.click("table.dnd-party [data-act=open-pc]"); await gm.wait_for_timeout(300)
        await gm.fill(".dnd-dmg input", "5"); await gm.click("[data-act=dnd-dmg]"); await gm.wait_for_timeout(200)
        ok(await gm.evaluate("dndCalc(st.party[0]).hp") == 15, "the GM can damage a party member from their sheet")
        await gm.screenshot(path=OUT + "/s8-gm-sheet.png", full_page=True)
        ring = await gm.evaluate("dndTokenRing({kind:'pc',ref:st.party[0].id})"); print(ring)
        ok(ring and ring["color"] == "#5fae4a" and abs(ring["frac"] - 0.75) < 0.01, "map token ring shows 15/20 HP")
        print("errors:", errs)
        ok(not errs, "no page errors")
        await b.close()
    sys.exit(finish())

asyncio.run(main())
